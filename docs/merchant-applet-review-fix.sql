--
-- 原理：小程序登录弹窗有「账号密码登录」，审核员用手机号 + 密码即可进入。
--       测试账号就是一条普通会员记录，只是给它设了 member.password。
--       正式上线时只需改密码或停用账号，无需改任何代码。
