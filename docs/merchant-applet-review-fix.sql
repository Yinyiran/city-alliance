-- ---------------------------------------------------------------------------
-- 1) 挑选测试账号
--    硬性条件（商家端必须满足，否则登录后提示「当前账号未开通企业端权限」）：
--       - is_delete = 0
--       - 有手机号（账号密码登录用手机号匹配）
--       - 是某店铺的老板或员工（shop.member_id / shop_employee）
--
--    用户端无此要求，普通会员即可。
-- ---------------------------------------------------------------------------
SELECT
    m.member_id,
    m.nickname,
    m.mobile,
    s.site_id,
    s.shop_name
FROM member m
LEFT JOIN shop s ON s.member_id = m.member_id
WHERE m.is_delete = 0
  AND m.mobile <> ''
ORDER BY m.member_id DESC
LIMIT 20;


